// Generates email-safe-templates.generated.ts for the worker and the api,
// inlining every HTML file from SlideAIemail/emails/email-safe/ as a string
// constant. Run by npm `prebuild` (and `prestart`) hooks. See WORKER_PATCH for
// rationale (Railway root-directory deploys do not include SlideAIemail/).

import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(__dirname, '..', '..');
const srcDir = join(repoRoot, 'SlideAIemail', 'emails', 'email-safe');

const outputs = [
  join(repoRoot, 'Backend', 'apps', 'worker', 'src', 'email-safe-templates.generated.ts'),
  join(repoRoot, 'Backend', 'apps', 'api', 'src', 'ops', 'email-safe-templates.generated.ts'),
];

const files = readdirSync(srcDir)
  .filter((file) => file.endsWith('.html'))
  .sort();

if (files.length === 0) {
  console.error(`[generate-email-templates] No .html files found in ${srcDir}`);
  process.exit(1);
}

const entries = files
  .map((file) => {
    const html = readFileSync(join(srcDir, file), 'utf8');
    return `  ${JSON.stringify(file)}: ${JSON.stringify(html)},`;
  })
  .join('\n');

const banner =
  '// AUTO-GENERATED by Backend/scripts/generate-email-templates.mjs\n' +
  '// Do not edit by hand. Regenerated by npm prebuild/prestart hooks.\n\n';

const body = `export const EMAIL_SAFE_TEMPLATES: Record<string, string> = {\n${entries}\n};\n`;

for (const outPath of outputs) {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, banner + body, 'utf8');
  console.log(`[generate-email-templates] Wrote ${outPath} (${files.length} templates)`);
}
